#!/usr/bin/env node
// Generate a typed list of bb's built-in host icon names for a plugin.
//
// bb's `experimental_Icon` renders icons by name but the SDK exports no list of
// valid names (get-bb/bb#1859). This script reads them from a bb source
// checkout at a release tag and writes a TypeScript module so plugin icon
// wrappers are typed against real names and a typo fails at compile time.
//
// Usage:
//   node scripts/host-icon-names.mjs --tag desktop-v0.43.1 --plugin sidebar
//   node scripts/host-icon-names.mjs --bb /path/to/bb-src --out plugins/plans/lib/host-icon-names.ts
//
// --tag <tag>        shallow-clone https://github.com/get-bb/bb at that tag into a temp dir
// --bb <dir>         use an existing bb source checkout instead of cloning
// --plugin <name>    write plugins/<name>/lib/host-icon-names.ts (repeatable)
// --out <file>       write to an explicit path (repeatable)
// --check            exit 1 if any target differs from the generated output
//
// Re-run on each bb upgrade and commit the diff.

import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, existsSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

const args = process.argv.slice(2);
const opts = { tag: null, bb: null, targets: [], check: false };
for (let i = 0; i < args.length; i += 1) {
  const a = args[i];
  const next = () => {
    i += 1;
    if (i >= args.length) throw new Error(`${a} needs a value`);
    return args[i];
  };
  if (a === "--tag") opts.tag = next();
  else if (a === "--bb") opts.bb = next();
  else if (a === "--plugin") opts.targets.push(join("plugins", next(), "lib", "host-icon-names.ts"));
  else if (a === "--out") opts.targets.push(next());
  else if (a === "--check") opts.check = true;
  else throw new Error(`unknown argument ${a}`);
}
if (!opts.tag && !opts.bb) throw new Error("pass --tag <tag> or --bb <dir>");
if (opts.targets.length === 0) throw new Error("pass at least one --plugin <name> or --out <file>");

let source = opts.bb;
if (!source) {
  source = join(mkdtempSync(join(tmpdir(), "bb-src-")), "bb");
  execFileSync("git", ["clone", "--quiet", "--depth", "1", "--branch", opts.tag, "https://github.com/get-bb/bb", source], { stdio: "inherit" });
}
const commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const tag = opts.tag ?? execFileSync("git", ["-C", source, "describe", "--tags", "--always"], { encoding: "utf8" }).trim();

const uiDir = join(source, "packages", "shared-ui", "src", "components", "ui");
const iconTsx = readFileSync(join(uiDir, "icon.tsx"), "utf8");
const registry = readFileSync(join(uiDir, "icon-registry.ts"), "utf8");

function block(text, start, end) {
  const from = text.indexOf(start);
  if (from < 0) throw new Error(`could not find ${JSON.stringify(start)}`);
  const to = text.indexOf(end, from + start.length);
  if (to < 0) throw new Error(`could not find ${JSON.stringify(end)} after ${JSON.stringify(start)}`);
  return text.slice(from + start.length, to);
}

const core = [...block(iconTsx, "const CORE_ICON_MAP = {", "\n}").matchAll(/^\s+([A-Za-z0-9_]+):/gm)].map(m => m[1]);
const extended = [...block(registry, "export const EXTENDED_ICON_NAMES = [", "\n]").matchAll(/"([^"]+)"/g)].map(m => m[1]);
if (core.length === 0 || extended.length === 0) throw new Error(`parsed ${core.length} core and ${extended.length} extended names; bb layout changed?`);
const names = [...new Set([...core, ...extended])].sort((a, b) => a.localeCompare(b));

const out = [
  `// Generated by scripts/host-icon-names.mjs from bb ${tag} (${commit}). Do not edit by hand.`,
  `// ${core.length} core names from packages/shared-ui/src/components/ui/icon.tsx and ${extended.length} extended names from icon-registry.ts.`,
  "",
  "export const HOST_ICON_SOURCE = {",
  `  tag: ${JSON.stringify(tag)},`,
  `  commit: ${JSON.stringify(commit)},`,
  "} as const;",
  "",
  "export const HOST_ICON_NAMES = [",
  ...names.map(n => `  ${JSON.stringify(n)},`),
  "] as const;",
  "",
  "export type HostIconName = (typeof HOST_ICON_NAMES)[number];",
  "",
  "export function isHostIconName(name: string): name is HostIconName {",
  "  return (HOST_ICON_NAMES as readonly string[]).includes(name);",
  "}",
  "",
].join("\n");

let stale = 0;
for (const target of opts.targets) {
  const path = resolve(target);
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (opts.check) {
    if (current !== out) {
      stale += 1;
      console.error(`stale: ${target}`);
    }
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, out);
  console.log(`${current === out ? "unchanged" : "wrote"}: ${target} (${names.length} names from ${tag})`);
}
if (opts.check) {
  if (stale) process.exit(1);
  console.log(`up to date: ${opts.targets.length} target(s), ${names.length} names from ${tag}`);
}
